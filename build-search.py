#!/usr/bin/env python3
"""Build search-index.js, the data behind the site-wide search (search.js).

Run it after changing any page's content:  python3 build-search.py
It reads the module pages, splits them into sections and sub-sections, and adds
every glossary term from reference.html. Standard library only.
"""
import html, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGES = [
    ("how-ai-agents-work.html", "1 · How AI agents work"),
    ("langchain-langgraph-langfuse.html", "2 · The three tools"),
    ("langchain.html", "3 · LangChain in depth"),
    ("langgraph.html", "4 · LangGraph in depth"),
    ("langfuse.html", "5 · Langfuse in depth"),
    ("metrics.html", "6 · Wealth AI metrics"),
    ("ship.html", "7 · Shipping an agent"),
    ("security.html", "9 · Agent security"),
    ("reference.html", "Glossary"),
]

def text_of(fragment):
    fragment = re.sub(r"<(script|style|svg)\b.*?</\1>", " ", fragment, flags=re.S)
    fragment = re.sub(r"</(p|li|div|h[1-6]|dt|dd|tr|pre|figcaption)>", "\n", fragment)
    fragment = re.sub(r"<[^>]+>", " ", fragment)
    return re.sub(r"\s+", " ", html.unescape(fragment)).strip()

def main_html(src):
    return src[src.index("<main"):src.rindex("</main>")]

def sections(src):
    """Yield (anchor, section_html) for every <section id="..."> inside <main>."""
    body = main_html(src)
    starts = [(m.start(), m.group(1)) for m in re.finditer(r'<section\b[^>]*\bid="([^"]+)"', body)]
    for i, (pos, anchor) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(body)
        yield anchor, body[pos:end]

def chunks(anchor, sec):
    """Split one section at its h3 headings: (h2 heading, h3 sub-heading, text)."""
    h2 = re.search(r"<h2\b[^>]*>(.*?)</h2>", sec, re.S)
    heading = text_of(h2.group(1)) if h2 else anchor
    if anchor == "demo":                      # index only the demo's intro, not its controls
        head = re.search(r'<div class="stage-head">.*?</div>|<div class="blk-head">.*?</div>', sec, re.S)
        sec = head.group(0) if head else ""
    parts = re.split(r"(<h3\b[^>]*>.*?</h3>)", sec, flags=re.S)
    out, sub = [], ""
    for part in parts:
        if part.startswith("<h3"):
            sub = text_of(part)
            continue
        t = text_of(part)
        if t:
            out.append((heading, sub, t))
    return out

def metrics_categories(src):
    """Module 6 renders its seven categories from a JS array, so read the data directly."""
    js = src[src.index("const CATS = ["):]
    js = js[len("const CATS = "):js.index("\n];") + 2]
    js = re.sub(r'T\("[^"]*",\s*("(?:[^"\\]|\\.)*")\)', r"\1", js)   # T("key","label") -> "label"
    js = re.sub(r'"\s*\+\s*"', "", js)                                # join "a"+"b"
    js = re.sub(r'([{,]\s*)([a-z]+):', r'\1"\2":', js)               # quote object keys
    cats = json.loads(js)
    for c in cats:
        lines = [c["why"], c["take"]] + [" ".join(m[1:4]) for m in c["m"]]
        yield c["id"], c["name"], "Owner: %s. %s" % (c["owner"], " ".join(lines))

def build():
    pages = [p for p, _ in PAGES]
    labels = [l for _, l in PAGES]
    entries = []
    for i, (page, _) in enumerate(PAGES):
        src = (ROOT / page).read_text(encoding="utf-8")
        if page == "reference.html":
            terms = json.loads(re.search(r"const TERMS = (\[.*?\]);\n", src, re.S).group(1))
            for t in terms:
                entries.append({"p": i, "a": "", "h": t["t"], "s": "", "t": t["d"], "g": 1})
            continue
        for anchor, sec in sections(src):
            for heading, sub, t in chunks(anchor, sec):
                entries.append({"p": i, "a": anchor, "h": heading, "s": sub, "t": t})
        if page == "metrics.html":
            for anchor, name, t in metrics_categories(src):
                entries.append({"p": i, "a": anchor, "h": name, "s": "", "t": t})
    data = {"pages": pages, "labels": labels, "entries": entries}
    out = "/* Generated by build-search.py. Do not edit by hand. */\nwindow.GUIDES_INDEX = " + \
          json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (ROOT / "search-index.js").write_text(out, encoding="utf-8")
    n_terms = sum(1 for e in entries if e.get("g"))
    print("search-index.js: %d sections, %d glossary terms, %.0f KB" % (len(entries) - n_terms, n_terms, len(out.encode()) / 1024))

if __name__ == "__main__":
    build()
